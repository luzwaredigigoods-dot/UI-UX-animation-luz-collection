#!/usr/bin/env node
/* Generate luz-motion-data.js (compact catalog + preview family per animation)
   from gallery/demos/*.js. Run after `node gallery/check.js`. */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const dir = path.join(__dirname, '..', 'gallery', 'demos');
const all = [];
const dupCtx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'gallery', 'duplikat.js'), 'utf8'), dupCtx);
const DUP = dupCtx.window.LUZ_DUPLIKAT || {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort()) {
  vm.runInNewContext(fs.readFileSync(path.join(dir, f), 'utf8'), { LUZ: { add: e => { if (!DUP[e.id]) all.push(e); } } });
}
// Preview family: how to approximate this animation on an arbitrary real element.
// Order matters: first matching rule wins.
const RULES = [
  [/circle-reveal|bloom|ripple-reveal|ink-bloom|halo-trace/, 'lingkar'],
  [/stagger|zipper|cascade|expand-all|fold-down|chain|block-build|rating-tags|tags|map-peek|resize-steps/, 'beruntun'],
  [/shake|buzz|jitter|glitch|zigzag/, 'getar'],
  [/wobble|tilt|swing|pendulum|message-drop/, 'goyang'],
  [/flip|coin|tumble|cube|page-turn|flap|twist/, 'balik'],
  [/hinge|double-doors|blinds|unroll|paper/, 'engsel'],
  [/line-unfold|line-expand|fold-open|outline|trace|border|comet|scan|select-sweep/, 'garis'],
  [/wipe|liquid-fill|water|flow-fill|sweep|side-slide|slide-shift|slice|split/, 'sapu'],
  [/sheet|drawer|swipe-back|push-back|stack|depth|slide/, 'geser'],
  [/blur|focus|dissolve|mosaic|pixel|dust|decode|melt/, 'kabur'],
  [/jelly|elastic|stretch|rubber|squeeze|goo|liquid|drip/, 'kenyal'],
  [/drop|land|fall|elastic-drop|rise/, 'jatuh'],
  [/burst|confetti|spark|halo|sonar|echo|glow|star/, 'denyar'],
  [/count|odometer|roll|counter|number|price|score/, 'gulir'],
  [/press|pop|spring|bounce|pogo|inset|dent|key|scale|grow|tick|check/, 'tekan'],
];
const BY_CAT = { 'Menu & Navigasi': 'beruntun', 'Tombol & Toggle': 'tekan', 'Input & Form': 'garis', 'List & Gesture': 'geser',
  'Kartu & Konten': 'geser', 'Modal, Sheet & Tooltip': 'muncul', 'Feedback & Notifikasi': 'muncul', 'Loading & Skeleton': 'kabur',
  'Teks & Angka': 'gulir', 'Transisi Halaman': 'geser', 'Latar & Efek': 'denyar', 'Prinsip Gerak': 'beruntun' };
const out = all.map(e => {
  const key = e.id + ' ' + e.name.toLowerCase().replace(/\s+/g, '-');
  const r = RULES.find(([re]) => re.test(key));
  const cut = s => (s.length > 150 ? s.slice(0, 147).replace(/\s\S*$/, '') + '…' : s);
  return { id: e.id, n: e.name, c: e.cat, t: e.trigger, d: e.timing, u: cut(e.use), g: r ? r[1] : (BY_CAT[e.cat] || 'muncul') };
});
const js = '/* Generated by koreksi-motion/build.js — do not edit by hand. */\n' +
  'window.LUZ_MOTION_DATA = ' + JSON.stringify(out).replace(/\},\{/g, '},\n{') + ';\n' +
  'window.LUZ_MOTION_ALIAS = ' + JSON.stringify(Object.fromEntries(Object.entries(DUP).map(([k, v]) => [k, v[0]]))) + ';\n';
fs.writeFileSync(path.join(__dirname, 'luz-motion-data.js'), js);
const fam = {}; out.forEach(o => fam[o.g] = (fam[o.g] || 0) + 1);
console.log(out.length + ' entries →', JSON.stringify(fam));
